-- Minimal Supabase-compatible PostgreSQL fixture for migration regression tests.
create role anon nologin;
create role authenticated nologin;
create role service_role nologin;
create role supabase_admin nologin;

create schema auth;
create schema private;
create table auth.users (id uuid primary key);

create or replace function auth.uid()
returns uuid
language sql
stable
as $$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
$$;

create table private.ghoustory_app_admins (user_id uuid primary key);
create or replace function private.is_ghoustory_app_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from private.ghoustory_app_admins
    where user_id = (select auth.uid())
  )
$$;
grant execute on function private.is_ghoustory_app_admin() to authenticated;

create table public.ghoustory_ai_usage (
  id bigint generated by default as identity primary key,
  user_id uuid,
  provider text,
  model text,
  feature text,
  input_tokens integer,
  output_tokens integer,
  status text,
  created_at timestamptz default now()
);
alter table public.ghoustory_ai_usage enable row level security;
create policy "Admins read AI usage" on public.ghoustory_ai_usage
  for select to authenticated using ((select private.is_ghoustory_app_admin()));
grant select on public.ghoustory_ai_usage to authenticated;

create table public.permission_probe (id integer primary key);
grant select, insert, update, delete, truncate on public.permission_probe to anon, authenticated;
