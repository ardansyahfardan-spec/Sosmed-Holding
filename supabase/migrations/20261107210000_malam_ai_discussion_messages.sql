create table if not exists public.malam_ai_messages (
  id bigint generated by default as identity primary key,
  room_id uuid not null,
  round_no integer not null,
  player_id uuid not null,
  nickname text not null,
  body text not null check (char_length(body) between 1 and 500),
  created_at timestamptz not null default now(),
  constraint malam_ai_messages_player_fk
    foreign key (room_id, player_id)
    references public.malam_players(room_id, user_id)
    on delete cascade,
  constraint malam_ai_messages_once_per_round
    unique (room_id, round_no, player_id)
);
create index if not exists malam_ai_messages_room_round_idx
  on public.malam_ai_messages(room_id, round_no, created_at);

alter table public.malam_ai_messages enable row level security;
grant select on public.malam_ai_messages to authenticated;
drop policy if exists malam_ai_messages_member_read on public.malam_ai_messages;
create policy malam_ai_messages_member_read
  on public.malam_ai_messages for select to authenticated
  using (
    exists (
      select 1 from public.malam_players p
      where p.room_id = malam_ai_messages.room_id
        and p.user_id = (select auth.uid())
        and not p.is_ai
    )
  );

create or replace function private.malam_seed_ai_discussion()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if new.phase = 'discussion' and old.phase is distinct from new.phase then
    insert into public.malam_ai_messages(room_id, round_no, player_id, nickname, body)
    select
      new.id,
      new.round_no,
      p.user_id,
      p.nickname,
      case x.role
        when 'siluman' then
          case (abs(hashtext(p.user_id::text || ':' || new.round_no::text)) % 3)
            when 0 then 'Aku tidak melihat siapa pun keluar tadi malam. Jangan buru-buru menuduh.'
            when 1 then 'Menurutku kita harus tetap tenang dan dengarkan alibi semua orang.'
            else 'Tuduhan tanpa bukti justru bisa membuat warga salah memilih.'
          end
        when 'paranormal' then
          case (abs(hashtext(p.user_id::text || ':' || new.round_no::text)) % 3)
            when 0 then 'Ada sesuatu yang terasa janggal dari kejadian semalam. Coba cocokkan alibi.'
            when 1 then 'Kita perlu memperhatikan siapa yang ceritanya berubah.'
            else 'Aku punya firasat ada yang menyembunyikan sesuatu.'
          end
        when 'penjaga' then
          case (abs(hashtext(p.user_id::text || ':' || new.round_no::text)) % 3)
            when 0 then 'Kita harus lebih teliti. Jangan sampai salah menuduh warga.'
            when 1 then 'Aku ingin tahu siapa yang paling diuntungkan dari kejadian tadi malam.'
            else 'Sebaiknya dengarkan semua orang sebelum menentukan pilihan.'
          end
        else
          case (abs(hashtext(p.user_id::text || ':' || new.round_no::text)) % 4)
            when 0 then 'Sebelum menuduh, kita cocokkan cerita masing-masing.'
            when 1 then 'Apa ada yang melihat sesuatu sebelum fajar?'
            when 2 then 'Menurutku kita perlu meminta alibi satu per satu.'
            else 'Aku masih ragu. Ada beberapa hal yang belum masuk akal.'
          end
      end
    from public.malam_players p
    join private.malam_roles x
      on x.room_id = p.room_id and x.user_id = p.user_id
    where p.room_id = new.id
      and p.is_ai
      and p.is_alive
    on conflict (room_id, round_no, player_id) do nothing;
  end if;
  return new;
end
$function$;

revoke all on function private.malam_seed_ai_discussion() from public, anon, authenticated;
drop trigger if exists malam_seed_ai_discussion_after_phase on public.malam_rooms;
create trigger malam_seed_ai_discussion_after_phase
  after update of phase on public.malam_rooms
  for each row
  when (new.phase = 'discussion' and old.phase is distinct from new.phase)
  execute function private.malam_seed_ai_discussion();